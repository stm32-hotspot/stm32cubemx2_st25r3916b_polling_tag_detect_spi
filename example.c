/**
  * The init of ST25R3916 is triggered by the applicative code
  * The initialization code is generated by STM32CubeMX2 under the targets folder.
  * All the aliases used here are generated by STM32CubeMX2 under the targets folder: see stm32_mcu_def.h.
  * output: EXEC_STATUS_INIT_OK if OK, EXEC_STATUS_ERROR in case of error
  */

app_status_t app_init(void)
{

  hal_exti_handle_t *pEXTI = mx_st25r3916_exti_gethandle();

  if (pEXTI == NULL)
  {
    return EXEC_STATUS_ERROR;
  }
  /* Associates user callback function to any interrupt edge event*/
  mx_gpio_default_init();
  if (HAL_EXTI_RegisterTriggerCallback(pEXTI, &HAL_EXTI_Rising_Callback) != HAL_OK)
  {
    return EXEC_STATUS_ERROR;
  }
  if (HAL_EXTI_Enable(pEXTI, HAL_EXTI_MODE_INTERRUPT) != HAL_OK)
  {
    return EXEC_STATUS_ERROR;
  }

  st25r3916_drv_obj_init();
  logUsartInit(BASIC_STDIO_UART_GETHANDLE());

  PLATFORM_LOG("Welcome to X-NUCLEO-NFC08A1\r\n");

  /* Initialize RFAL */
  if (!demoIni())
  {
    /*
    * in case the rfal initialization failed signal it by flashing all LED
    * and stopping all operations
    */
    PLATFORM_LOG("Initialization failed..\r\n");
    while (1)
    {
      PLATFORM_DELAY(100);
    }
  }
  else
  {
    PLATFORM_LOG("Initialization succeeded..\r\n");
    PLATFORM_LOG("Hold NFC Card/Tag Near NFC Reader..\r\n");
    for (int32_t i = 0; i < 6; i++)
    {
      PLATFORM_DELAY(200);
    }

  }

  return EXEC_STATUS_INIT_OK;
}

